# Objetivo: Informa se um número é positivo ou negativo

# Pede para o usuário digitar u número inteiro
numero = int (input ("Digite um número: "))

# Decisão 1: Se o número for maior ou igual a 0
if numero >= 0:
    print ("Positivo")
# Decisão 2: Se o número for menor que 0
else:
    print ("Negativo")