# Objetivo: Informa se um número é par ou ímpar

# Pede um número ao usuário
numero = int (input ("Digite um número: "))

# Decisão 1: Se o número for ímpar
if numero % 2 == 1:
    print ("Número ímpar")
# Decisão 2: Se o número for par
else:
    print ("Número par")