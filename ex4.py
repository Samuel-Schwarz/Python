# Objetivo: Calcular a média de três notas informadas pelo usuário

# Pede a temperatura em Celsius, e salva isso na variável "c"
c = float (input ("Escreva a temperatura em Celsius: "))

# Calcula a temperatura em Fahrenheits
f = c * 1.8 + 32

# Informa o resultado ao usuário
print ("Em Fahrenheits, a temperatura é:", f)